// ── Create a form via Marketing Forms API v3 ─────────────────────────────────
async function createForm({ name, fields }) {
  const body = {
    name,
    formType: "hubspot",
    fieldGroups: [
      {
        groupType: "default_group",
        richTextType: "text",
        fields,
      },
    ],
    configuration: {
      language: "en",
      cloneable: false,
      postSubmitAction: { type: "thank_you", value: "Thanks for reaching out!" },
    },
  };

  const res = await apiRequest("POST", "/marketing/v3/forms", body);
  if (res.status !== 201 && res.status !== 200) {
    throw new Error(
      `Failed to create form "${name}": ${res.status} – ${JSON.stringify(res.body)}`
    );
  }
  return res.body.id; // GUID
}

